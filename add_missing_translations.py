with open('src/lib/languages.ts', 'r', encoding='utf-8') as f:
    content = f.read()

# For each language, add the missing translations
for lang_code, translations in missing_translations.items():
    # Find the language section
    lang_pattern = f"  {lang_code}: {{"
    if lang_pattern in content:
        # Find the closing brace of this language section
        start_idx = content.find(lang_pattern)
        brace_count = 0
        i = start_idx + len(lang_pattern)

        # Find matching closing brace
        while i < len(content):
            if content[i] == '{':
                brace_count += 1
            elif content[i] == '}':
                if brace_count == 0:
                    # Found the closing brace
                    # Add translations
                    new_translations = []
                    for key, value in translations.items():
                        # Check if this key already exists
                        key_pattern = f"    {key}:"
                        section = content[start_idx:i]
                        if key_pattern not in section:
                            # Escape single quotes in the value
                            escaped_value = value.replace("'", "\\'")
                            new_translations.append(f"    {key}: '{escaped_value}',")

                    if new_translations:
                        # Insert before the closing brace
                        insertion = '\n' + '\n'.join(new_translations) + '\n  '
                        content = content[:i] + insertion + content[i:]
                    break
                else:
                    brace_count -= 1
            i += 1

# Write the updated content back
with open('src/lib/languages.ts', 'w', encoding='utf-8') as f:
    f.write(content)

print("Missing translations added successfully!")
print(f"Updated {len(missing_translations)} languages")
